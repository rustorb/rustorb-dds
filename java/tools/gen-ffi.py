#!/usr/bin/env python3
"""Writes java/src/main/java/org/rustorb/dds/Ffi.java: a downcall handle
for each function of the C ABI (crates/rustorb-dds-ffi/include/rustorb/dds.h)
that the binding uses (the names Ffi.rdds_... its sources mention).

    java/tools/gen-ffi.py          # rewrite Ffi.java
    java/tools/gen-ffi.py --check  # fail if Ffi.java is not up to date

Pointers are passed as Java longs (JAVA_LONG), which all the 64-bit
targets of rustorb-dds pass like pointers; the handles of the binding are
longs too. The array and string parameters of the sample streams are
ADDRESS instead, for heap segments (Java arrays) passed to the critical
functions below. Structs passed by value (rdds_duration,
rdds_instance_handle) are their layouts.

Licensed under MIT OR Apache-2.0, like the rest of rustorb-dds.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "crates/rustorb-dds-ffi/include/rustorb/dds.h"
SOURCES = ROOT / "java/src/main/java/org/rustorb/dds"
OUTPUT = SOURCES / "Ffi.java"

SCALARS = {
    "bool": "JAVA_BOOLEAN",
    "char": "JAVA_BYTE",
    "int8_t": "JAVA_BYTE",
    "uint8_t": "JAVA_BYTE",
    "int16_t": "JAVA_SHORT",
    "uint16_t": "JAVA_SHORT",
    "int32_t": "JAVA_INT",
    "uint32_t": "JAVA_INT",
    "rdds_status": "JAVA_INT",
    "int64_t": "JAVA_LONG",
    "uint64_t": "JAVA_LONG",
    "size_t": "JAVA_LONG",
    "float": "JAVA_FLOAT",
    "double": "JAVA_DOUBLE",
}
BY_VALUE = {"rdds_duration": "Ffi.DURATION", "rdds_instance_handle": "Ffi.HANDLE"}


def critical(name):
    """Short functions that neither call back into Java nor block."""
    if name.startswith(("rdds_out_", "rdds_in_")):
        return name not in ("rdds_out_new", "rdds_out_release", "rdds_in_release")
    return name in ("rdds_last_error_message", "rdds_condition_trigger_value",
                    "rdds_condition_equals", "rdds_samples_count", "rdds_samples_info",
                    "rdds_abi_version")


def heap(name, param):
    """Parameters that may be Java arrays (heap segments)."""
    return critical(name) and param == "v" and (
        name.endswith("_array") or name in ("rdds_out_string", "rdds_out_wstring"))


def layout(ctype, name, param):
    ctype = ctype.replace("const ", "").strip()
    if "*" in ctype or "[" in param:
        return "ADDRESS" if heap(name, param) else "JAVA_LONG"
    if ctype in SCALARS:
        return SCALARS[ctype]
    if ctype in BY_VALUE:
        return BY_VALUE[ctype]
    raise SystemExit("gen-ffi: no layout for %r in %s" % (ctype, name))


def prototypes():
    text = HEADER.read_text()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"^#.*$", "", text, flags=re.M)
    out = {}
    for m in re.finditer(r"([A-Za-z_][\w \*]*?)\b(rdds_\w+)\s*\(([^;{]*?)\)\s*;", text):
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        if ret.startswith("typedef") or "(" in params:
            continue
        ps = []
        if params != "void":
            for p in params.split(","):
                p = " ".join(p.split())
                pm = re.match(r"(.*?)(\w+)(\[\d+\])?$", p)
                ctype, pname, arr = pm.group(1), pm.group(2), pm.group(3) or ""
                ps.append(layout(ctype, name, pname + arr))
        r = None if ret == "void" else layout(ret, name, "")
        out[name] = (r, ps)
    return out


def used():
    names = set()
    for f in SOURCES.rglob("*.java"):
        if f.name == "Ffi.java":
            continue
        names.update(re.findall(r"\bFfi\.(rdds_\w+)", f.read_text()))
    return names


def generate():
    protos = prototypes()
    names = sorted(used())
    missing = [n for n in names if n not in protos]
    if missing:
        raise SystemExit("gen-ffi: not in dds.h: " + ", ".join(missing))
    lines = [
        "// Generated by java/tools/gen-ffi.py from crates/rustorb-dds-ffi/include/rustorb/dds.h.",
        "// Do not edit.",
        "//",
        "// Licensed under MIT OR Apache-2.0, like the rest of rustorb-dds.",
        "",
        "package org.rustorb.dds;",
        "",
        "import static java.lang.foreign.ValueLayout.ADDRESS;",
        "import static java.lang.foreign.ValueLayout.JAVA_BOOLEAN;",
        "import static java.lang.foreign.ValueLayout.JAVA_BYTE;",
        "import static java.lang.foreign.ValueLayout.JAVA_DOUBLE;",
        "import static java.lang.foreign.ValueLayout.JAVA_FLOAT;",
        "import static java.lang.foreign.ValueLayout.JAVA_INT;",
        "import static java.lang.foreign.ValueLayout.JAVA_LONG;",
        "import static java.lang.foreign.ValueLayout.JAVA_SHORT;",
        "",
        "import java.lang.foreign.FunctionDescriptor;",
        "import java.lang.foreign.MemoryLayout;",
        "import java.lang.foreign.StructLayout;",
        "import java.lang.invoke.MethodHandle;",
        "",
        "@SuppressWarnings(\"unused\")",
        "final class Ffi {",
        "    private Ffi() {}",
        "",
        "    /** rdds_duration and rdds_time. */",
        "    static final StructLayout DURATION = MemoryLayout.structLayout(",
        "            JAVA_INT.withName(\"sec\"), JAVA_INT.withName(\"nanosec\"));",
        "    /** rdds_instance_handle and rdds_guid. */",
        "    static final StructLayout HANDLE = MemoryLayout.structLayout(",
        "            MemoryLayout.sequenceLayout(16, JAVA_BYTE).withName(\"value\"));",
        "",
    ]
    for n in names:
        r, ps = protos[n]
        args = ", ".join(ps)
        if r is None:
            fd = "FunctionDescriptor.ofVoid(%s)" % args
        else:
            fd = "FunctionDescriptor.of(%s)" % ", ".join([r] + ps)
        opt = ""
        if critical(n):
            opt = ", Library.CRITICAL_HEAP" if "ADDRESS" in ps else ", Library.CRITICAL"
        lines.append("    static final MethodHandle %s = Library.fn(\"%s\", %s%s);" % (n, n, fd, opt))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.stderr.write("gen-ffi: %s is not up to date; run java/tools/gen-ffi.py\n" % OUTPUT)
            sys.exit(1)
        return
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
